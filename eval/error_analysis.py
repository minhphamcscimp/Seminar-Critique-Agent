"""Error analysis for report Section 5.7. Owner: Tam.

    python -m eval.error_analysis            # after eval.runner and eval.judge

For every run without a pipeline error and every key point the phrase scorer did not
find in the final answer, assign one category:

    paraphrase           the LLM judge says the point is covered (scorer artefact)
    lost between agents  the phrase appears in an intermediate step but not in the answer
    not produced         neither of the above

Pipeline errors (verdict = error) are counted per run. Writes
eval/results/error_analysis.md with counts, shares per config, 2-3 examples per category
(task_id, run_id, trace), and the lowest-scoring runs to read by hand (the plan asks for
>= 10 traces read manually; fill the "Manual category" column while reading).
"""
from __future__ import annotations

import argparse
import csv
import json
from collections import Counter, defaultdict
from pathlib import Path

from .judge import load_tasks
from .keypoint_trace import _has

CATEGORIES = ("paraphrase", "lost between agents", "not produced")


def classify(rows: list[dict], judge: dict[str, dict], tasks: dict) -> tuple[list[dict], list[dict], int]:
    """Return (key-point misses, error runs, runs whose trace file is missing)."""
    misses, errors, missing = [], [], 0
    for row in rows:
        if row.get("error"):
            errors.append(row)
            continue
        task = tasks.get(row["task_id"])
        path = Path(row.get("trace_path", ""))
        if task is None or not path.is_file():
            missing += 1
            continue
        trace = json.loads(path.read_text(encoding="utf-8"))
        answer = trace.get("answer", "")
        steps = [s["output"] for s in trace.get("trace", [])[:-1]]  # all but the last step
        labels = judge.get(row["run_id"], {}).get("point_labels", "")
        for i, kp in enumerate(task.key_points):
            if _has(kp, answer):
                continue
            if len(labels) == len(task.key_points) and labels[i] == "1":
                category = "paraphrase"
            elif any(_has(kp, s) for s in steps):
                category = "lost between agents"
            else:
                category = "not produced"
            misses.append({"run_id": row["run_id"], "task_id": row["task_id"], "config": row["config"],
                           "key_point": kp, "category": category, "trace_path": path.as_posix()})
    return misses, errors, missing


def render(rows: list[dict], judge: dict[str, dict], tasks: dict, n_manual: int = 10) -> str:
    misses, errors, missing = classify(rows, judge, tasks)
    configs = sorted({r["config"] for r in rows})
    lines = ["# Error analysis (Section 5.7)", "",
             "Generated by `python -m eval.error_analysis`. A miss = a key point the phrase scorer "
             "did not find in the final answer of a run without a pipeline error.", ""]
    if not judge:
        lines += ["**No judge.csv: 'paraphrase' cannot be detected; run `python -m eval.judge` first.**", ""]
    if missing:
        lines += [f"**{missing} run(s) skipped: trace file not found** (traces/ is not committed).", ""]

    by_cfg = defaultdict(Counter)
    for m in misses:
        by_cfg[m["config"]][m["category"]] += 1
    total = len(misses)
    lines += ["## Key-point misses by category", "",
              "| Category | " + " | ".join(configs) + " | All | Share |",
              "| --- | " + " | ".join("---" for _ in configs) + " | --- | --- |"]
    for cat in CATEGORIES:
        n = sum(by_cfg[c][cat] for c in configs)
        share = f"{n / total:.0%}" if total else "n/a"
        lines.append(f"| {cat} | " + " | ".join(str(by_cfg[c][cat]) for c in configs) + f" | {n} | {share} |")
    lines.append(f"| **total misses** | " + " | ".join(str(sum(by_cfg[c].values())) for c in configs)
                 + f" | {total} | |")
    lines += ["", f"Pipeline errors: {len(errors)} of {len(rows)} runs."]
    for e in errors[:5]:
        lines.append(f"- `{e['run_id']}`: {e['error']}")
    lines += ["", "## Examples", ""]
    for cat in CATEGORIES:
        examples = [m for m in misses if m["category"] == cat][:3]
        if examples:
            lines.append(f"**{cat}**")
            lines += [f"- `{m['task_id']}` config {m['config']}: \"{m['key_point']}\" (`{m['run_id']}`, "
                      f"`{m['trace_path']}`)" for m in examples]
            lines.append("")

    def run_score(r: dict) -> float:
        j = judge.get(r["run_id"], {})
        value = j.get("judge_score") or r.get("score") or r.get("key_point_recall") or 0
        return float(value)

    worst = sorted((r for r in rows if not r.get("error")), key=lambda r: (run_score(r), r["run_id"]))
    manual = errors[:n_manual] + worst[: max(0, n_manual - len(errors))]
    lines += ["## Traces to read by hand", "",
              "Lowest judge score (phrase score if no judge), pipeline errors first.", "",
              "| run_id | Score | Trace | Manual category | Note |", "| --- | --- | --- | --- | --- |"]
    for r in manual:
        score = "error" if r.get("error") else f"{run_score(r):.2f}"
        lines.append(f"| {r['run_id']} | {score} | `{r.get('trace_path', '')}` |  |  |")
    return "\n".join(lines) + "\n"


def main() -> None:
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--results", default="eval/results/results.csv")
    p.add_argument("--judge", default="eval/results/judge.csv")
    p.add_argument("--tasks", default="eval/tasks")
    p.add_argument("--out", default="eval/results/error_analysis.md")
    p.add_argument("--n-manual", type=int, default=10)
    args = p.parse_args()

    with open(args.results, newline="", encoding="utf-8") as f:
        rows = list(csv.DictReader(f))
    if rows and "trace_path" not in rows[0]:
        p.error(f"{args.results} is in the D2 format (no trace_path); run eval.runner first")
    judge: dict[str, dict] = {}
    if Path(args.judge).exists():
        with open(args.judge, newline="", encoding="utf-8") as f:
            judge = {r["run_id"]: r for r in csv.DictReader(f) if not r["error"]}
    text = render(rows, judge, load_tasks(args.tasks), args.n_manual)
    Path(args.out).write_text(text, encoding="utf-8")
    print(text, end="")
    print(f"wrote {args.out}")


if __name__ == "__main__":
    main()
