"""Write eval/TASKS.md: the task list for the team (Minh: retrieval, Tin: R1, Van: configs).

    python -m eval.task_table

Re-run after editing tasks or after benchmark records / PAPER_BENCHMARKS change, so the
"benchmark evidence" column is current.
"""
from __future__ import annotations

from collections import Counter
from datetime import date
from pathlib import Path

from seminar_critique.orchestrator import _lookup_benchmarks

from .judge import load_tasks


def render(tasks_dir: str = "eval/tasks") -> str:
    tasks = sorted(load_tasks(tasks_dir).values(), key=lambda t: (t.topic, t.paper, t.id))
    found = {}
    for t in tasks:
        names = sorted({c["args"]["name"] for c in _lookup_benchmarks(t) if c["result"].get("found")})
        found[t.id] = ", ".join(names)
    topics = Counter(t.topic for t in tasks)
    papers = Counter(t.paper for t in tasks)
    diff = Counter(t.difficulty for t in tasks)
    n_found = sum(bool(v) for v in found.values())
    lines = [
        "# Eval task list (D3)",
        "",
        f"Generated by `python -m eval.task_table` on {date.today().isoformat()}. "
        "Source of truth: the JSON files in `eval/tasks/`.",
        "",
        f"- {len(tasks)} tasks: " + ", ".join(f"{k} {v}" for k, v in sorted(topics.items())) + ".",
        "- Tasks per paper: " + ", ".join(f"{k} {v}" for k, v in sorted(papers.items())) + ".",
        "- Difficulty: " + ", ".join(f"{k} {v}" for k, v in sorted(diff.items())) + ".",
        f"- Benchmark tool finds evidence today (R1): **{n_found}/{len(tasks)}** tasks "
        f"({n_found / len(tasks):.0%}); target >= 50%. The orchestrator picks benchmarks from "
        "`PAPER_BENCHMARKS` (regex on the task input), so new records in `data/benchmarks.json` "
        "also need a mapping there; `task.paper` gives the paper id directly.",
        "",
        "| Task | Topic | Paper | Difficulty | Key points | Benchmark evidence today |",
        "| --- | --- | --- | --- | --- | --- |",
    ]
    for t in tasks:
        lines.append(f"| {t.id} | {t.topic} | {t.paper} | {t.difficulty} | "
                     f"{'; '.join(t.key_points)} | {found[t.id] or '-'} |")
    return "\n".join(lines) + "\n"


def main() -> None:
    text = render()
    Path("eval/TASKS.md").write_text(text, encoding="utf-8")
    print(text, end="")


if __name__ == "__main__":
    main()
